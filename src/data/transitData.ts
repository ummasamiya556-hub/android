// ==========================================
// FARE & PASS CALCULATOR
// ==========================================
export function calculateFareBreakdown(tngFareRm: number, passType: CommuterPassType): FareBreakdown {
  const baseTng = Math.max(0, Math.round(tngFareRm * 100) / 100);
  const cashRm = Math.max(1.00, Math.round((baseTng * 1.25 + 0.30) * 10) / 10);
  const concessionRm = Math.round((baseTng * 0.5) * 10) / 10;
  const isMy50Covered = true; // My50 covers all Rapid KL buses, LRT, MRT, Monorail & Klang Valley KTM services

  let savingsRm = 0;
  if (passType === 'my50') {
    savingsRm = baseTng; // Instant marginal savings
  } else if (passType === 'concession') {
    savingsRm = Math.round((baseTng - concessionRm) * 100) / 100;
  } else if (passType === 'tng') {
    savingsRm = Math.round((cashRm - baseTng) * 100) / 100;
  }

  return {
    tngRm: baseTng,
    cashRm,
    concessionRm,
    my50Covered: isMy50Covered,
    savingsRm: Math.max(0, savingsRm),
  };
}

// ==========================================
// CROWD DENSITY & 24H RUSH HOUR CURVE
// ==========================================
export function getCrowdDensity(customTime?: Date): CrowdDensity {
  const now = customTime || new Date();
  const hours = now.getHours();
  const minutes = now.getMinutes();
  const timeDecimal = hours + minutes / 60;

  // Morning Rush: 07:15 to 09:30
  if (timeDecimal >= 7.25 && timeDecimal <= 9.5) {
    const intensity = Math.round(82 + Math.sin(((timeDecimal - 7.25) / 2.25) * Math.PI) * 16);
    return {
      level: 'packed',
      percentage: Math.min(98, intensity),
      isPeakHour: true,
      peakLabel: 'Morning Rush Hour (Peak Commute)',
      recommendation: 'Heavy platform density. Allow +3 to +5 mins for boarding queue. Priority seating strictly observed.',
    };
  }

  // Evening Rush: 17:15 to 19:45
  if (timeDecimal >= 17.25 && timeDecimal <= 19.75) {
    const intensity = Math.round(80 + Math.sin(((timeDecimal - 17.25) / 2.5) * Math.PI) * 15);
    return {
      level: 'packed',
      percentage: Math.min(95, intensity),
      isPeakHour: true,
      peakLabel: 'Evening Rush Hour (Suburban Dispersal)',
      recommendation: 'Packed southbound carriages towards KL Sentral & Seremban. Rapid KL Bus 190 recommended as bypass if platform crowded.',
    };
  }

  // Mid-day Lunch / Early Afternoon: 11:30 to 14:00
  if (timeDecimal >= 11.5 && timeDecimal <= 14.0) {
    return {
      level: 'moderate',
      percentage: 54,
      isPeakHour: false,
      peakLabel: 'Lunch Period (Moderate Traffic)',
      recommendation: 'Steady passenger flow with available seating on majority of coaches.',
    };
  }

  // Late Evening / Early Morning Off-peak
  return {
    level: 'low',
    percentage: 26,
    isPeakHour: false,
    peakLabel: 'Off-Peak Window (Comfortable Transit)',
    recommendation: 'Light patronage. Immediate seating and quick ticket gate passage.',
  };
}

